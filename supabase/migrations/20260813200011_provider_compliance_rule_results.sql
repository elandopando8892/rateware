create table if not exists public.provider_compliance_rule_results (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete restrict,
  evaluation_id uuid not null,
  rule_set_id uuid not null,
  rule_id uuid not null,
  rule_code_snapshot text not null,
  rule_name_snapshot text not null,
  category_snapshot text not null,
  severity_snapshot text not null,
  evaluator_code_snapshot text not null,
  is_required_snapshot boolean not null,
  is_blocking_snapshot boolean not null,
  continuous_snapshot boolean not null,
  result text not null default 'unknown',
  explanation text,
  evaluated_at timestamptz,
  valid_until timestamptz,
  reviewed_at timestamptz,
  reviewed_by_user_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint provider_compliance_rule_results_org_id_unique unique (organization_id,id),
  constraint provider_compliance_rule_results_evaluation_fkey foreign key (organization_id,evaluation_id,rule_set_id) references public.provider_compliance_evaluations(organization_id,id,rule_set_id) on delete cascade,
  constraint provider_compliance_rule_results_rule_fkey foreign key (organization_id,rule_id,rule_set_id) references public.provider_compliance_rules(organization_id,id,rule_set_id) on delete restrict,
  constraint provider_compliance_rule_results_rule_unique unique (organization_id,evaluation_id,rule_id),
  constraint provider_compliance_rule_results_code_check check (rule_code_snapshot ~ '^[a-z][a-z0-9_]{1,127}$'),
  constraint provider_compliance_rule_results_name_not_blank check (btrim(rule_name_snapshot) <> ''),
  constraint provider_compliance_rule_results_category_check check (category_snapshot ~ '^[a-z][a-z0-9_]{1,63}$'),
  constraint provider_compliance_rule_results_severity_check check (severity_snapshot in ('info','low','medium','high','critical')),
  constraint provider_compliance_rule_results_evaluator_check check (evaluator_code_snapshot ~ '^[a-z][a-z0-9_]{1,127}$'),
  constraint provider_compliance_rule_results_result_check check (result in ('unknown','pass','fail','warn','review','error')),
  constraint provider_compliance_rule_results_evaluated_check check (result='unknown' or evaluated_at is not null),
  constraint provider_compliance_rule_results_review_check check (result <> 'review' or (reviewed_at is not null and nullif(btrim(coalesce(reviewed_by_user_id,'')),'') is not null))
);

create index if not exists provider_compliance_rule_results_evaluation_idx
  on public.provider_compliance_rule_results (evaluation_id,result,severity_snapshot,rule_code_snapshot);
